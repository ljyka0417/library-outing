/**
 * 운영시간 파서 회귀 시험.
 *
 *   npm run test-hours
 *
 * 여기 적힌 문장은 전부 정보나루에서 실제로 내려온 것이다.
 * 파서를 손볼 때마다 이걸 돌려서, 읽던 걸 못 읽게 되거나 **틀리게 읽게**
 * 되지 않았는지 본다.
 *
 * ⚠️ "포기" 도 정답이다.
 *   틀린 운영시간은 사람을 헛걸음시킨다. 모르는 문장은 읽지 않는 것이
 *   맞고, 그때 화면은 배지 없이 원문만 보여준다.
 *   실제로 욕심내다가 어린이자료실 시간을 주말 시간으로 넣고, 토·일을
 *   통째로 휴관 처리한 적이 있다.
 */

import { parseHours } from './lib/hours.mjs';

/** [문장, 기대값] — 기대값은 "화/토/일" 순서의 닫는 시각, 또는 '포기' */
const CASES = [
  // ── 읽어야 하는 것 ──────────────────────────────────────
  ['09:00~18:00', '18/18/18'],
  ['9:00~18:00', '18/18/18'],
  ['오전 9시 ~ 오후 6시', '18/18/18'],
  ['평일 09:00~22:00, 주말 09:00~18:00', '22/18/18'],
  ['주중 09:00~21:00, 주말 09:00~18:00', '21/18/18'],
  ['평일 ( 09:00 ~ 22:00 ) / 주말 ( 09:00 ~ 18:00 )', '22/18/18'],
  ['(평일) 09:00~18:00 (주말) 09:00~17:00', '18/17/17'],
  ['평일 09:00 ~ 22:00, 토일 09:00 ~ 17:00', '22/17/17'],
  ['월~금 09:00 ~ 18:00 토,일 09:00 ~ 17:00', '18/17/17'],
  ['09:00 ~ 18:00, 토/일요일 09:00 ~ 17:00', '18/17/17'],
  ['평일 : 오전9시~오후6시 / 주말 : 오전9시~오후5시', '18/17/17'],
  ['화~금(9:00~22:00) / 토,일(9:00~18:00)', '22/18/18'],
  ['평일(화~금) 09:00~22:00, 주말(토,일) 09:00~18:00', '22/18/18'],
  ['화~금 09:00~21:00 / 토,일 09:00~18:00', '21/18/18'],
  ['화요일~금요일 09:00~22:00, 토요일 09:00~18:00, 일요일 09:00~17:00', '22/18/17'],
  ['화,수,금,토,일요일 : 10:00 ~18:00 / 목 : 10:00 ~ 20:00', '18/18/18'],
  ['화~일요일 09:00~18:00', '18/18/18'],
  ['09:00~18:00(자료실) / 07:00~22:00(일반열람실)', '18/18/18'],

  // ── 읽지 말아야 하는 것 ─────────────────────────────────
  ['-', '포기'],
  ['06:00~23:00(하절기), 07:00~23:00(동절기)', '포기'],
  ['종합자료실 09:00~22:00(주말 17:00), 어린이실 09:00~18:00(주말 17:00), 열람실 07:00~22:00', '포기'],
  ['자료실 월-금 09:00~22:00 주말/공휴일 09:00~18:00, 열람실 07:00~24:00', '포기'],
  ['월~금 09:00~22:00, 토 09:00~20:00 일요일 09:00~18:00 (일부실 연장운영중)', '포기'],
  ['평일 09:00~20:00(유아실·어린이실 09:00~18:00), 주말 09:00~17:00', '포기'],
  ['[자료실] 09:00~18:00 (종합자료실, 어린이자료실은 평일 09:00~22:00 연장), [열람실] 07:00~22:00', '포기'],
  ['종합자료실,어린이실-9:00~18:00(토,일요일-17:00)/학습실-07:00~22:00', '포기'],
];

const hourOf = (v) => (v === null ? '휴' : String(Math.floor(v.close / 60)));

let pass = 0;
const failed = [];

for (const [text, expect] of CASES) {
  const h = parseHours(text);
  const got =
    h.byDay.length === 7 ? `${hourOf(h.byDay[2])}/${hourOf(h.byDay[6])}/${hourOf(h.byDay[0])}` : '포기';

  if (got === expect) pass++;
  else failed.push({ text, expect, got });
}

console.log(`운영시간 파서 — ${pass}/${CASES.length} 통과\n`);
for (const f of failed) {
  console.log(`  기대 ${f.expect.padEnd(10)} 실제 ${f.got.padEnd(10)} ← ${f.text.slice(0, 60)}`);
}

if (failed.length > 0) {
  console.log('\n(기대값은 "화요일/토요일/일요일 의 닫는 시각" 입니다)');
  process.exit(1);
}
